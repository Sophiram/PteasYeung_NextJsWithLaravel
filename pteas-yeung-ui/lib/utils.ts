/**
 * Truncate text to a maximum length
 */
export function truncate(text: string, maxLength: number): string {
  if (text.length <= maxLength) return text;
  return text.slice(0, maxLength) + '...';
}

/**
 * Get API error message from axios/RTK Query error
 */
export function getErrorMessage(error: unknown): string {
  if (error && typeof error === 'object') {
    const err = error as Record<string, unknown>;
    if ('data' in err && err.data && typeof err.data === 'object') {
      const data = err.data as Record<string, unknown>;
      if ('message' in data && typeof data.message === 'string') {
        return data.message;
      }
      if ('errors' in data && data.errors && typeof data.errors === 'object') {
        const errors = data.errors as Record<string, string[]>;
        return Object.values(errors).flat().join(', ');
      }
    }
    if ('message' in err && typeof err.message === 'string') {
      return err.message;
    }
  }
  return 'An unexpected error occurred. Please try again.';
}

/**
 * Format and normalize uploaded image URLs (Storage / CDN / MinIO)
 */
export function getOptimizedImageUrl(rawImage?: string | null): string | null {
  if (!rawImage) return null;
  const storageBaseUrl = (process.env.NEXT_PUBLIC_STORAGE_URL || 'http://localhost:8000/storage').replace(/\/$/, '');

  // Fix accidental localhost without port 8000 when generated by Laravel CLI
  if (rawImage.startsWith('http://localhost/storage/') || rawImage.startsWith('http://127.0.0.1/storage/')) {
    return rawImage.replace(/http:\/\/(localhost|127\.0\.0\.1)\/storage/, storageBaseUrl);
  }

  // Full MinIO / S3 / External CDN URLs
  if (rawImage.startsWith('http://') || rawImage.startsWith('https://')) {
    return rawImage;
  }

  // Relative storage paths
  const cleanPath = rawImage.replace(/^\/?(storage\/)?/, '');
  return `${storageBaseUrl}/${cleanPath}`;
}

/**
 * Trigger an in-browser download of a Blob file
 */
export function downloadBlobFile(blobData: BlobPart, filename: string, mimeType = 'application/octet-stream') {
  const blob = new Blob([blobData], { type: mimeType });
  const downloadUrl = window.URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = downloadUrl;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();
  window.URL.revokeObjectURL(downloadUrl);
}
