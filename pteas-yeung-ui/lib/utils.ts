// lib/utils.ts
import { clsx, type ClassValue } from 'clsx';
import { twMerge } from 'tailwind-merge';

/**
 * shadcn/ui required utility: merges Tailwind classes intelligently
 */
export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}

/**
 * Format a number as currency (USD by default)
 */
export function formatCurrency(amount: string | number, currency = 'USD'): string {
  return new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency,
    minimumFractionDigits: 2,
  }).format(Number(amount));
}

/**
 * Format a date string to local readable format
 */
export function formatDate(dateString: string | null | undefined, locale = 'km-KH'): string {
  if (!dateString) return '—';
  return new Date(dateString).toLocaleDateString(locale);
}

/**
 * Get status badge variant based on payment status
 */
export function getPaymentStatusVariant(status: string): 'default' | 'secondary' | 'destructive' | 'outline' {
  switch (status) {
    case 'paid':
      return 'default';
    case 'unpaid':
      return 'destructive';
    case 'partial':
      return 'secondary';
    default:
      return 'outline';
  }
}

